// حارسٌ واحدٌ لكلِّ الصور: أيُّ صورةٍ يفشلُ تحميلُها تُستبدَلُ ببديلٍ يشبهُ التصميم
// بدل أيقونةِ المتصفّحِ المكسورة.
//
// كُتب حين عُطّل حسابُ Cloudinary لتجاوزِ الحصّة، فذهبت صورُ الموقعِ كلُّها دفعةً
// واحدةً وصار المتجرُ لوحةَ علاماتِ تعجّبٍ أمام الزبائن. بطاقةُ المنتجِ وحدَها كانت
// تحرسُ صورَها؛ والباقي — شعارُ المتجرِ في الشريط، والصورُ الشخصيّة، والتصنيفات،
// واللافتات — بلا حارس: نحوُ أربعين صورةً في اثنين وعشرين ملفّاً.
//
// ولأنّ الحاجةَ واحدةٌ في كلِّ موضع، حارسٌ واحدٌ في الجذرِ أصدقُ من أربعين تعديلاً
// متفرّقاً: حدثُ error لا يصعدُ (bubble) لكنّه يُلتقَطُ في مرحلةِ الهبوط (capture)،
// فمستمعٌ واحدٌ على المستندِ يرى كلَّ صورةٍ في التطبيق — وما يُضافُ لاحقاً كذلك،
// بلا أن يتذكّرَ أحدٌ إضافةَ onError.

// بديلٌ محايدٌ بألوانِ المنصّة: قرميديٌّ كريميٌّ ورسمُ جبلٍ وشمسٍ خفيفٌ بالبنّي.
// SVG مضمّنٌ لا ملفّ: لا طلبَ شبكةٍ إضافيّاً — وهو المطلوبُ في لحظةٍ يكونُ فيها
// مصدرُ الصورِ نفسُه ساقطاً.
const FALLBACK =
  'data:image/svg+xml;utf8,' +
  encodeURIComponent(
    '<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400">' +
      '<rect width="400" height="400" fill="#f1e9dd"/>' +
      '<g fill="none" stroke="#b9a68c" stroke-width="10" stroke-linejoin="round" stroke-linecap="round">' +
      '<rect x="96" y="116" width="208" height="168" rx="16"/>' +
      '<path d="M116 246l52-48 40 34 36-30 40 38"/>' +
      '</g>' +
      '<circle cx="164" cy="166" r="15" fill="#b9a68c"/>' +
    '</svg>'
  );

export function installImageFallback() {
  document.addEventListener(
    'error',
    (e) => {
      const el = e.target;
      // الحدثُ في مرحلةِ الالتقاطِ يمرُّ على كلِّ ما يفشلُ تحميلُه (نصوصٌ وأنماطٌ
      // وصور)، فلا نتدخّلُ إلّا في الصور.
      if (!el || el.tagName !== 'IMG') return;
      // مرّةً واحدةً لكلِّ صورة: البديلُ نفسُه لو فشل لدارت الحلقةُ بلا نهاية.
      if (el.dataset.bzFallback) return;
      // صورةٌ تحرسُ نفسَها (onError خاصٌّ بها وضع بديلَه) — لا نُبدّلُ اختيارَها.
      if (el.currentSrc && el.currentSrc.startsWith('data:')) return;
      el.dataset.bzFallback = '1';
      el.removeAttribute('srcset'); // وإلّا اختارَ المتصفّحُ من القائمةِ الساقطةِ ثانيةً
      el.removeAttribute('sizes');
      // حذفُ src قبل إسنادِ البديل: الإسنادُ وحدَه — والمتصفّحُ ما زال داخلَ معالجةِ
      // التحميلِ الفاشل — لا يثبت، فيبقى العنصرُ فارغاً (naturalWidth = 0) ويظهرُ
      // مكسوراً كما كان. حذفُ السمةِ يُنهي الحالةَ الساقطةَ فيبدأُ تحميلُ البديلِ نظيفاً.
      el.removeAttribute('src');
      el.src = FALLBACK;
    },
    true // الالتقاطُ — حدثُ error لا يصعدُ من الصورةِ إلى المستند
  );
}
