// تنظيفُ ما خلّفَته نسخةٌ سابقة. «تذكّرني» كانت تحفظُ كلمةَ المرورِ نفسَها في
// localStorage تحتَ bz_remember_pw (بترميزِ base64، وهو تمويهٌ لا تعمية: من
// يقرأُ المفتاحَ يقرأُ الكلمة). أيُّ ثغرةِ XSS على النطاقِ كانت تكفي لسحبِها،
// وكانت تبقى على الجهازِ المشتركِ أو المسروقِ إلى ما لا نهاية.
//
// الكتابةُ أُزيلت من صفحةِ الدخول، لكنَّ القيمةَ القديمةَ لا تزولُ من أجهزةِ من
// سجّلَ دخولَه قبلَ اليوم إلّا بمسحٍ صريح — فنمسحُها عندَ أوّلِ إقلاعٍ بعدَ
// التحديث. bz_remember_email يبقى: البريدُ يُعبّئُ الحقلَ ولا يفتحُ باباً.
const LEGACY_KEYS = ['bz_remember_pw'];

export function purgeLegacyStorage() {
  try {
    for (const k of LEGACY_KEYS) localStorage.removeItem(k);
  } catch { /* تصفّح خاص */ }
}
