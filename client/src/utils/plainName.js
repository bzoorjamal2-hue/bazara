// اسمٌ يقرؤُه محرّكُ البحث — نسخةُ الواجهةِ من ‎server/src/utils/plainName.js
//
// تكتبُ التاجرةُ اسمَ متجرِها بحروفٍ زخرفيّةٍ من لوحاتِ الإنترنت — «𝓗𝓪𝓫𝓸𝓸𝓼𝓱
// 𝓢𝓽𝔂𝓵𝓮» — وهي بنظرِ يونيكود حروفٌ أخرى تماماً ‎(U+1D4D7) لا علاقةَ لها
// بـ‎H اللاتينيّة. فمن يبحثُ عن «Haboosh Style» لا يطابقُ شيئاً.
//
// ‏NFKD يفكُّها إلى أصولِها اللاتينيّةِ ويترك العربيّةَ كما هي، ثمّ نحذفُ
// العلاماتِ المُركَّبةَ الناتجةَ عن الفكِّ — والتشكيلُ العربيُّ المكتوبُ أصلاً
// يبقى لأنّه لا يمرُّ بهذا الفكّ.
//
// والاسمُ المعروضُ بالمتجرِ لا يتغيّر: هذا للعنوانِ ووسومِ البحثِ والبياناتِ
// المنظَّمةِ فقط، فيبقى شكلُ المتجرِ كما اختارته وتصيرُ نتيجةُ البحثِ مطابِقة.
export function plainName(s) {
  const raw = String(s || '').trim();
  if (!raw) return '';
  const out = raw
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return out || raw;
}
