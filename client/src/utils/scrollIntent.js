/* ═══════ نيّةُ التمرير: أينزل القارئ أم يعود؟ ═══════
   منطقٌ نقيٌّ بلا نافذةٍ ولا رياكت، كي يُختبر وحدَه: يأخذ الموضعَ الجديد ويردّ
   ما ينبغي أن يصيرَه الشريطُ العلويّ (مخفيّاً · ظاهراً) أو null إن لم تنضج
   النيّةُ بعد فيبقى على حاله.

   نقيس مجموعَ الحركة باتّجاهٍ واحد لا الفرقَ بين فريمين: الإصبعُ على الشاشة
   يرتجف، والفرقُ الخامُ يجعل الشريطَ يرفرف ظهوراً واختفاءً بكلّ سحبة. وانعكاسُ
   الاتّجاه يصفّر العدّاد، فتبدأ النيّةُ الجديدةُ من الصفر لا من رصيدِ سابقتها. */

export const MIN_Y = 72;       // رأسُ الصفحة يبقى كاملاً: لا اختفاءَ قبل هذا العمق
export const HIDE_DELTA = 12;  // نزولٌ متّصلٌ بهذا المقدار يُخفي
export const SHOW_DELTA = 6;   // رفعةٌ صغيرةٌ تكفي للعودة — الرفعُ نيّةُ عودةٍ لا حركةٌ عابرة
export const JUMP = 200;       // قفزةٌ مفاجئة (استعادةُ موضعٍ · تمريرٌ برمجيّ) لا نيّةَ فيها

export function createIntent(y = 0) {
  return { lastY: Math.max(0, y), acc: 0 };
}

export function readIntent(m, rawY) {
  const y = Math.max(0, rawY);
  const dy = y - m.lastY;
  m.lastY = y;

  // حارسُ القمّة أوّلاً لا أخيراً: رأسُ الصفحة يُظهر الشريطَ مهما كانت الحركةُ
  // التي أوصلت إليه — ولو كانت قفزةً واحدة يبتلعها حارسُ القفزة أدناه.
  if (y <= MIN_Y) { m.acc = 0; return false; }
  if (!dy) return null;
  if (Math.abs(dy) > JUMP) { m.acc = 0; return null; }

  if ((m.acc > 0) !== (dy > 0)) m.acc = 0;
  m.acc += dy;
  if (m.acc > HIDE_DELTA) return true;
  if (m.acc < -SHOW_DELTA) return false;
  return null;
}
