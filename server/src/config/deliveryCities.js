// إزالة تكرار المدن بالاسم (احتياطاً) — يبقى أول ظهور
const _seen = new Set();
const _TREE = PS_CITY_TREE.filter((x) => (x.name && !_seen.has(x.name)) ? (_seen.add(x.name), true) : false);

// خريطة اسم المدينة → الشريحة (بحث سريع عند إعادة حساب الأجرة على الخادم)
const NAME_TIER = new Map(_TREE.map((x) => [x.name, x.tier]));

// خريطة اسم القرية → مدينتها. تخدم أمرين: (١) الطلبات القديمة اللي كانت تحفظ اسم
// القرية بحقل "المدينة" فتظل أجرتها تُحسب صح، و(٢) تحديد المدينة تلقائياً لو وصل
// اسم قرية فقط. أول ظهور يفوز (ما في قرية بمدينتين).
const VILLAGE_CITY = new Map();
for (const x of _TREE) for (const v of x.villages) if (v && !VILLAGE_CITY.has(v)) VILLAGE_CITY.set(v, x.name);

// تطبيع أسعار الشرائح القادمة من الإعداد (٣ أرقام غير سالبة) مع القيم الافتراضية
export function normalizeTiers(raw) {
  const t = raw && typeof raw === 'object' ? raw : {};
  const num = (v, d) => {
    const n = Number(v);
    return Number.isFinite(n) && n >= 0 ? n : d;
  };
  return {
    wb: num(t.wb, DELIVERY_TIER_DEFAULTS.wb),
    quds: num(t.quds, DELIVERY_TIER_DEFAULTS.quds),
    dakhel: num(t.dakhel, DELIVERY_TIER_DEFAULTS.dakhel),
  };
}

// أجرة مدينة: استثناء المتجر (zones) أولاً، ثم سعر الشريحة، ثم شريحة الضفة كافتراضي.
// لو وصل اسم قرية (طلب قديم) نُرجعه لمدينته قبل الحساب.
export function feeForCity(cityName, tiers, overrides) {
  const raw = String(cityName || '').trim();
  if (!raw) return 0;
  const name = NAME_TIER.has(raw) ? raw : (VILLAGE_CITY.get(raw) || raw);
  const ov = Array.isArray(overrides) ? overrides.find((z) => z && (z.name === raw || z.name === name)) : null;
  if (ov && ov.fee != null && ov.fee !== '') return Math.max(0, Number(ov.fee) || 0);
  const tier = NAME_TIER.get(name);
  const tt = normalizeTiers(tiers);
  return tier ? tt[tier] : tt.wb;
}

// المدن الرئيسية فقط مع أجرتها — هي اللي تظهر ببحث المدينة عند الزبون والتاجر
export function citiesWithFees(tiers, overrides) {
  const tt = normalizeTiers(tiers);
  return _TREE.map((x) => ({ name: x.name, tier: x.tier, region: x.region, fee: feeForCity(x.name, tt, overrides) }));
}

// خريطة { اسم المدينة: [قراها] } — تُرسل للواجهة ليختار الزبون قريته بعد المدينة
export function villagesByCity() {
  const out = {};
  for (const x of _TREE) out[x.name] = x.villages;
  return out;
}

// المدينة التي تتبع لها قرية معيّنة (أو '' إن كانت غير معروفة)
export function cityOfVillage(name) {
  return VILLAGE_CITY.get(String(name || '').trim()) || '';
}
