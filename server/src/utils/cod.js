// مَن يقبضُ ماذا: قسمةُ مبلغِ الطلبِ بين البطاقةِ والمندوب.
//
// القاعدة: البطاقةُ تحملُ ثمنَ البضاعةِ وحدَه، ورسومُ التوصيلِ تُدفَعُ نقداً
// لشركةِ التوصيلِ عند وصولِ المندوب. فالشحنُ خدمةُ الشركةِ لا خدمةُ المتجر،
// وتحصيلُه إلكترونيّاً يعني أن يقبضَه المتجرُ ثمّ يردَّه للشركة — طريقٌ أطولُ
// وخلافٌ أكثر. والزبونُ يدفعُ للشركةِ مباشرةً كما جرت العادة.
//
// وهذه القسمةُ ليست رقماً بمكانٍ واحدٍ بل حقيقةٌ تظهرُ بستّةِ مواضع: صفحةُ
// الدفعِ (كم يُخصَم)، وزرُّ التأكيد، وشهادةُ الشراء، وصفحةُ العودة، وفاتورةُ
// المتجر، وأمرُ التحصيلِ المُرسَلُ لشركةِ التوصيل. فتُكتَبُ هنا مرّةً واحدةً
// وتقرأُها المواضعُ كلُّها، كي لا يفترقَ رقمٌ عن رقم.
//
// الطلبُ القديمُ (قبل عمود payment_method) يُعدُّ دفعاً عند الاستلامِ كما كان.

const num = (v) => Number(v || 0);

/** هل سُدِّد هذا الطلبُ إلكترونيّاً (ولو جزئيّاً)؟ */
export const isPrepaid = (order) => String(order?.payment_method ?? order?.paymentMethod ?? 'cod') === 'card';

/**
 * ثمنُ البضاعةِ بعد الخصم — وهو ما يُخصَمُ من البطاقةِ وحدَه.
 * يُحسَبُ من إجماليِّ الطلبِ ناقصَ التوصيل، فلا يحتاجُ عموداً جديداً ولا
 * يفترقُ عن المخزَّنِ مهما تغيّرت الخصومات.
 */
export const goodsAmount = (order) => Math.max(0, num(order?.total) - num(order?.delivery_fee ?? order?.deliveryFee));

/** ما سُدِّد إلكترونيّاً فعلاً: ثمنُ البضاعةِ للبطاقة، وصفرٌ للاستلام */
export const paidOnline = (order) => (isPrepaid(order) ? goodsAmount(order) : 0);

/**
 * ما يُحصّلُه المندوبُ عند الباب:
 *   بطاقة → رسومُ التوصيلِ وحدَها (البضاعةُ مدفوعة)
 *   استلام → إجماليُّ الطلب
 */
export const codAmount = (order) => (isPrepaid(order)
  ? num(order?.delivery_fee ?? order?.deliveryFee)
  : num(order?.total));

/** حقلا أوبتيموس معاً: العلَمُ والمبلغُ لا ينفصلان (علَمٌ مرفوعٌ بمبلغِ صفرٍ يُربكُ الشركة) */
export function codFields(order) {
  const amount = codAmount(order);
  return { is_cod: amount > 0 ? 1 : 0, cod_amount: amount };
}
