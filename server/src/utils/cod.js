// كم يُحصّلُ المندوبُ من الزبون عند الباب؟
//
// الطلبُ المدفوعُ بالبطاقةِ سُدِّد على صفحةِ البنكِ قبل أن يُشحَن، فلا شيءَ
// يُحصَّلُ عند التسليم. وكنّا نُرسلُ إجماليَّ الطلبِ لشركةِ التوصيلِ دائماً —
// لأوبتيموس وEPS وgobox — فيقفُ المندوبُ عند البابِ يطلبُ مبلغاً مدفوعاً:
// تحصيلٌ مرّتين، وخصامٌ مع الزبونة، ومالٌ يُردُّ بعد أخذٍ وردّ.
//
// القاعدةُ واحدةٌ للشركاتِ الثلاث فتُكتَبُ مرّةً واحدةً هنا: طريقةُ الدفعِ
// المحفوظةُ بالطلبِ هي الحَكَم، وما عدا 'card' يُحصَّل.

export const isPrepaid = (order) => String(order?.payment_method || 'cod') === 'card';

/** المبلغُ المطلوبُ تحصيلُه — صفرٌ للطلبِ المدفوعِ مسبقاً */
export const codAmount = (order) => (isPrepaid(order) ? 0 : Number(order?.total || 0));

/** حقلا أوبتيموس معاً: العلَمُ والمبلغُ لا ينفصلان (علَمٌ مرفوعٌ بمبلغِ صفرٍ يُربكُ الشركة) */
export function codFields(order) {
  const amount = codAmount(order);
  return { is_cod: amount > 0 ? 1 : 0, cod_amount: amount };
}
