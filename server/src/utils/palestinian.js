// ───────── المصفاة ─────────
//
// تُطبَّقُ على اللهجةِ الفلسطينيّةِ وحدَها: تاجرةٌ اختارت المصريّةَ لزبائنِها تريدُ
// «ده» و«عايزة»، وتحويلُهما عندَها إفسادٌ لا إصلاح.
export function palestinize(text, dialect = 'ps') {
  if (dialect !== 'ps') return text;
  let s = String(text || '');
  if (!s) return s;

  for (const [re, to] of PHRASES) s = s.replace(re, to);
  for (const [from, to] of FOREIGN) s = sub(s, from, to);
  for (const [from, to] of BOOKISH) s = sub(s, from, to);

  // «هل» أداةٌ لا يُدخِلُها المحكيُّ على سؤال: «هل بدّك تشوفي؟» → «بدّك تشوفي؟».
  // تُحذَفُ بحرفِها لا تُستبدَل، وما بعدَها يبقى كما هو.
  s = s.replace(/(^|[\s،.!؟])هل\s+/gu, '$1');

  // نداءٌ باسمٍ لاتينيٍّ: «يا Edaa» — لا أحدَ ينادي زبونتَه بحروفٍ أجنبيّةٍ بمحادثةٍ
  // عربيّة، وهو أوضحُ ما يفضحُ أنّ المتكلّمَ آلة. يُحذَفُ النداءُ ويبقى الكلام.
  s = s.replace(/\s*يا\s+[A-Za-z][A-Za-z._\-·]*\s*/gu, ' ');

  return s.replace(/[ \t]{2,}/g, ' ').replace(/ ([،.!؟])/g, '$1').trim();
}

