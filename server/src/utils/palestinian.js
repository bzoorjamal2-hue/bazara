// ═══════════════════ اللهجةُ الفلسطينيّة ═══════════════════
//
// زبونةٌ حقيقيّةٌ ضحكت على البائعةِ حتّى اضطرّت التاجرةُ أن تقاطعَ وتعتذرَ لها
// («في مشكله بالصفحه 🤣 بعتذر منك»). وسببُ الضحكِ مكتوبٌ بالمحادثةِ حرفاً حرفاً:
//
//   «شنو أخبارك؟»            ← عراقيّة/خليجيّة، والفلسطينيُّ يقولُ «شو»
//   «بتبغي تشوفي»            ← خليجيّة، والفلسطينيُّ يقولُ «بدّك»
//   «ما في مشكلة خالص»       ← مصريّة، والفلسطينيُّ يقولُ «ولا يهمّك»
//   «صورة اللون ده»          ← مصريّة، والفلسطينيُّ يقولُ «هاد»
//   «شوفي الصورة هسع»        ← شاميّة، والفلسطينيُّ يقولُ «هسّا»
//   «حسناً يا Edaa، بدي أوضح» ← ترجمةٌ لا كلامَ بشر
//
// جملةٌ واحدةٌ فيها أربعُ لهجاتٍ ليست لهجةً، هي لكنةُ آلةٍ تُقلّدُ العربَ كلَّهم
// معاً. وهذا ما لا يُغفَرُ لبائعةٍ تقفُ في محلٍّ برام الله.
//
// والعلاجُ طبقتان، لأنّ طبقةً واحدةً لا تكفي:
//   ١) وصفٌ دقيقٌ للنموذجِ — يُعلّمُه كيفَ يتكلّمُ أهلُ البلد، لا اسمَ اللهجةِ فقط.
//   ٢) مصفاةٌ حتميّةٌ بعدَه — لأنّ النموذجَ يزلُّ، ونحن لا نراهنُ على ألّا يزلّ.
//      وهي نفسُ قاعدةِ المنصّةِ كلِّها: النموذجُ يتكلّم، والخادمُ يقرّر.

// حدُّ الكلمةِ بالعربيّة: \b عديمُ الفائدةِ هنا لأنّه مبنيٌّ على ASCII، فحرفُ
// العينِ عندَه «حدّ». نحرسُ بأنفسِنا: لا حرفَ ولا حركةَ قبلَ الكلمةِ ولا بعدَها.
// وواوُ العطفِ وفاؤُه تلتصقانِ بالكلمةِ بالعربيّة، فتحجبانِ الحدَّ عن غيرِ قصد:
// «أيضاً» تُلتقَطُ و«وأيضاً» تُفلِت. فنسمحُ بهما بادئةً ونُعيدُهما كما كانتا.
const B = (w) => new RegExp(`(?<![\\p{L}\\p{M}])([وف]?)${w}(?![\\p{L}\\p{M}])`, 'gu');
const sub = (s, from, to) => s.replace(B(from), (_, p) => p + to);

// ───────── ١) عباراتٌ كاملةٌ تُستبدَلُ قبلَ المفردات ─────────
// الجملةُ أدقُّ من الكلمةِ حينَ تكونُ الكلمةُ وحدَها ملتبسة: «خالص» قد تعني
// «انتهى» وقد تعني «أبداً»، فلا تُمَسُّ إلّا داخلَ عبارةٍ لا لبسَ فيها.
