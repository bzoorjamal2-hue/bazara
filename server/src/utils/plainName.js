// اسمٌ يقرؤُه محرّكُ البحثِ لا يقرؤُه الذوقُ وحدَه.
//
// تكتبُ التاجرةُ اسمَ متجرِها بحروفٍ زخرفيّةٍ من لوحاتِ الإنترنت — «𝓗𝓪𝓫𝓸𝓸𝓼𝓱
// 𝓢𝓽𝔂𝓵𝓮» — وهي بنظرِ يونيكود حروفٌ أخرى تماماً ‎(U+1D4D7) لا علاقةَ لها
// بـ‎H اللاتينيّة. فمن يبحثُ عن «Haboosh Style» بجوجل لا يطابقُ شيئاً، ولو
// كان كلُّ شيءٍ آخرَ مضبوطاً: الخريطةُ والروبوتسُ والوسومُ كلُّها بلا فائدةٍ
// أمامَ اسمٍ لا يُطابِقُ ما يكتبُه الناس.
//
// ‏NFKD يفكُّ هذه الحروفَ إلى أصولِها اللاتينيّةِ ويترك العربيّةَ كما هي
// (فالعربيّةُ ليست زخرفةً بل حروفُها الأصليّة). ثمّ نحذفُ العلاماتِ المُركَّبةَ
// الناتجةَ عن الفكِّ وحدَها — لا التشكيلَ العربيَّ الأصليّ، إذ لا يظهرُ منه
// شيءٌ بعدَ الفكِّ ما لم يكن مكتوباً أصلاً.
//
// والاسمُ المعروضُ لا يتغيّر: هذا للعنوانِ والوصفِ والبياناتِ المنظَّمةِ فقط،
// فيبقى شكلُ المتجرِ كما اختارته وتصيرُ نتيجةُ البحثِ مقروءةً ومطابِقة.
export function plainName(s) {
  const raw = String(s || '').trim();
  if (!raw) return '';
  const out = raw
    .normalize('NFKD')
    // علاماتُ التشكيلِ الناتجةُ عن الفكِّ ‎(combining marks) تُحذَف
    .replace(/[̀-ͯ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return out || raw;
}

// وصفٌ قصيرٌ للبحث: اسمُ المتجرِ ثمّ وصفُه إن وُجد، وإلّا جملةٌ تقولُ ما هو.
// كان الوصفُ «الاسم — أزياء فاخرة» لكلِّ متجر: جملةٌ واحدةٌ تتكرّرُ على كلِّ
// متاجرِ المنصّة، ومحرّكُ البحثِ يخفضُ ترتيبَ الأوصافِ المكرّرة.
export function storeDescription(name, description, city) {
  const n = plainName(name);
  const d = String(description || '').replace(/\s+/g, ' ').trim();
  if (d) return `${n} — ${d}`.slice(0, 300);
  const where = city ? ` في ${city}` : ' في فلسطين';
  return `${n}: تسوّقي فساتين وأطقم وعبايات${where} — توصيل لكل فلسطين والدفع عند الاستلام.`;
}
